CREATE DATABASE Clase;
USE Clase;
CREATE TABLE Clientes(
id_cliente int NOT NULL IDENTITY (1,1) PRIMARY KEY, -- INT PORQUE EL ID ES UN NUMERO ENERO. QUE NO SE REPITE (NN).
nombre VARCHAR (100) NOT NULL, -- VARCHAR PORQUE EL NOMBRE TIENE UN DESARROLLO VARIADO.NO DEBERIA REPETIRSE (NN)
perfil_bio TEXT,  -- TEXT PARA DESARROLLO DE LA SINTAXIS LIBRE.
fecha_registro DATE -- DATE PARA UNA FECHA EXACTA. NO NOS INTERESA LA HORA. PUEDE REPETIRSE. 
);

SELECT * FROM Clientes;

CREATE TABLE productos(
id_producto int NOT NULL IDENTITY (1,1) PRIMARY KEY, -- INT PORQUE EL ID ES UN NUMERO ENERO. QUE NO SE REPITE (NN).
descripcion VARCHAR (255) NOT NULL, -- VARCHAR PORQUE TIENE UN DESARROLLO VARIADO.NO DEBERIA REPETIRSE (NN)
precio DECIMAL (10,2), -- SE BUSCA UN PRECIO QUE CONTENGA HASTA DIEZ DIGITOS Y A PARTE, DOS DECIMALES. PUEDE REPETIRSE 
esta_activo VARCHAR (9) -- SE BUSCA QUE FIGURE "ACTIVO" O "NO ACTIVO"
);